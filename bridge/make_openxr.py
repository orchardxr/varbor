#!/usr/bin/env python3
"""Generate wineopenxr's OpenXR thunks from xr.xml.

  make_openxr.py <xr.xml> <outdir>

Writes xr_thunks.h (call ids and parameter structs, shared by both sides), xr_thunks_pe.c and xr_thunks_unix.c.
Both sides are 64-bit with identical struct layouts and OpenXR handles pass through unchanged, so a generated thunk
only packs the arguments. Functions that need conversion or locking are hand-written (PE_MANUAL as wine_<name>, UNIX_CALLS).
"""
import os
import sys
import xml.etree.ElementTree as ET

# Hand-written unix calls bridge_<name> (src/wineopenxr_unix.c), placed before the generated ones.
UNIX_CALLS = [
    "init",
    "has_function",
    "create_instance",
    "destroy_instance",
    "create_session",
    "vk_unwrap",
    "vk_suggested_device",
    "time_sample",
    "dxmt_create_device",
    "dxmt_destroy_device",
    "dxmt_import_image",
    "dxmt_destroy_image",
    "dxmt_copy",
    "unsupported_device",
]

# Implemented on the PE side (src/wineopenxr.c); they may still use the generated unix thunk.
PE_MANUAL = {
    "xrGetInstanceProcAddr",
    "xrEnumerateInstanceExtensionProperties",
    "xrEnumerateApiLayerProperties",
    "xrCreateInstance",
    "xrDestroyInstance",
    "xrCreateSession",
    "xrDestroySession",
    "xrEnumerateSwapchainFormats",
    "xrCreateSwapchain",
    "xrDestroySwapchain",
    "xrEnumerateSwapchainImages",
    "xrAcquireSwapchainImage",
    "xrWaitSwapchainImage",
    "xrReleaseSwapchainImage",
    "xrEndFrame",
    "xrWaitFrame",
    "xrBeginFrame",
    "xrEndSession",
    "xrGetVulkanInstanceExtensionsKHR",
    "xrGetVulkanDeviceExtensionsKHR",
    "xrGetVulkanGraphicsDeviceKHR",
    "xrGetVulkanGraphicsDevice2KHR",
    "xrCreateVulkanInstanceKHR",
    "xrCreateVulkanDeviceKHR",
    "xrGetD3D11GraphicsRequirementsKHR",
    "xrConvertWin32PerformanceCounterToTimeKHR",
    "xrConvertTimeToWin32PerformanceCounterKHR",
}

# No unix thunk at all: replaced by a UNIX_CALLS entry, or PE-only.
UNIX_SKIP = {
    "xrGetInstanceProcAddr",
    "xrCreateInstance",
    "xrDestroyInstance",
    "xrCreateSession",
    "xrGetVulkanGraphicsDeviceKHR",
    "xrGetVulkanGraphicsDevice2KHR",
    "xrCreateVulkanInstanceKHR",
    "xrCreateVulkanDeviceKHR",
    "xrGetD3D11GraphicsRequirementsKHR",
    "xrConvertWin32PerformanceCounterToTimeKHR",
    "xrConvertTimeToWin32PerformanceCounterKHR",
}

# Extensions the bridge implements on the PE side, with their protect macro.
PE_EXTENSIONS = {
    "XR_KHR_D3D11_enable": "XR_USE_GRAPHICS_API_D3D11",
    "XR_KHR_win32_convert_performance_counter_time": "XR_USE_PLATFORM_WIN32",
}

# Host extensions games may see: unprotected or Vulkan ones, minus these.
HIDDEN = {
    "XR_EXT_debug_utils",  # the messenger callback would be called with the host ABI
    "XR_KHR_loader_init",
}
SAFE_PROTECT = {None, "XR_USE_GRAPHICS_API_VULKAN"}
# Used by the unix side only, never exposed.
HOST_ONLY = {"XR_KHR_convert_timespec_time"}


def param_decl(p):
    """('const XrFoo*', 'name', '[4]' or '')"""
    name = p.find("name").text
    text = "".join(p.itertext())
    pre, post = text.split(name, 1)
    return " ".join(pre.split()), name, post.strip()


def main():
    reg = ET.parse(sys.argv[1]).getroot()
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)

    commands, aliases = {}, {}
    for c in (c for block in reg.findall("commands") for c in block):
        if c.get("alias"):
            aliases[c.get("name")] = c.get("alias")
            continue
        name = c.find("proto/name").text
        commands[name] = [param_decl(p) for p in c.findall("param")]

    origin = {}  # command -> (extension or None, protect)
    for f in reg.findall("feature"):
        if f.get("name") == "XR_LOADER_VERSION_1_0":
            continue
        for cmd in f.iter("command"):
            origin.setdefault(cmd.get("name"), (None, None))
    visible_exts, host_only = [], []
    for e in reg.find("extensions"):
        if e.get("supported") != "openxr":
            continue
        ext, protect = e.get("name"), e.get("protect")
        if ext in HOST_ONLY:
            host_only += [cmd.get("name") for cmd in e.iter("command")]
            continue
        if ext in PE_EXTENSIONS:
            protect = PE_EXTENSIONS[ext]
        elif protect not in SAFE_PROTECT or ext in HIDDEN:
            continue
        else:
            visible_exts.append(ext)
        for cmd in e.iter("command"):
            origin.setdefault(cmd.get("name"), (ext, protect))

    names = sorted(n for n in origin if n in commands or n in aliases)
    real = [n for n in names if n in commands]
    host_side = [n for n in real if origin[n][1] in SAFE_PROTECT and n != "xrGetInstanceProcAddr"] + host_only

    with open(os.path.join(out, "xr_thunks.h"), "w") as h:
        h.write("/* Generated by bridge/make_openxr.py from xr.xml. */\n#pragma once\n\nenum unix_call\n{\n")
        for u in UNIX_CALLS:
            h.write(f"    unix_{u},\n")
        for n in real:
            if n not in UNIX_SKIP:
                h.write(f"    unix_{n},\n")
        h.write("    unix_count,\n};\n\n")
        for n in real:
            if n in UNIX_SKIP:
                continue
            prot = origin[n][1]
            if prot:
                h.write(f"#ifdef {prot}\n")
            h.write(f"struct {n}_params\n{{\n")
            for t, pn, arr in commands[n]:
                h.write(f"    {t} {'*' if arr else ''}{pn};\n")
            h.write("    XrResult result;\n};\n")
            if prot:
                h.write("#endif\n")
            h.write("\n")
        h.write("extern const char *const visible_host_extensions[];\n")
        h.write(f"#define VISIBLE_HOST_EXTENSION_COUNT {len(visible_exts)}\n")

    with open(os.path.join(out, "xr_thunks_pe.c"), "w") as c:
        c.write('/* Generated by bridge/make_openxr.py from xr.xml. */\n#include "wineopenxr_private.h"\n\n')
        for n in real:
            if n in PE_MANUAL:
                continue
            params = commands[n]
            sig = ", ".join(f"{t} {pn}{arr}" for t, pn, arr in params)
            c.write(f"static XrResult XRAPI_CALL thunk_{n}({sig})\n{{\n")
            c.write(f"    struct {n}_params p = {{{', '.join(pn for _, pn, _ in params)}}};\n")
            c.write(f"    UNIX_CALL({n}, &p);\n    return p.result;\n}}\n\n")
        c.write("const struct xr_function pe_functions[] =\n{\n")
        for n in names:
            target = aliases.get(n, n)
            ext, prot = origin[n]
            fn = f"wine_{target}" if target in PE_MANUAL else f"thunk_{target}"
            line = f'    {{"{n}", (PFN_xrVoidFunction){fn}, {f"{chr(34)}{ext}{chr(34)}" if ext else "NULL"}}},\n'
            if prot and prot not in SAFE_PROTECT:
                line = f"#ifdef {prot}\n{line}#endif\n"
            c.write(line)
        c.write("};\nconst unsigned int pe_function_count = ARRAY_SIZE(pe_functions);\n\n")
        c.write("const char *const visible_host_extensions[] =\n{\n")
        for e in visible_exts:
            c.write(f'    "{e}",\n')
        c.write("};\n")

    with open(os.path.join(out, "xr_thunks_unix.c"), "w") as c:
        c.write('/* Generated by bridge/make_openxr.py from xr.xml. */\n#include "wineopenxr_unix.h"\n\n')
        c.write("struct host_functions host;\n\nvoid host_load_functions(XrInstance instance)\n{\n")
        for n in host_side:
            c.write(f'    host_gipa(instance, "{n}", (PFN_xrVoidFunction *)&host.{n});\n')
        c.write("}\n\n")
        for n in real:
            if n in UNIX_SKIP:
                continue
            params = commands[n]
            args = ", ".join(f"p->{pn}" for _, pn, _ in params)
            c.write(f"static NTSTATUS thunk_{n}(void *args)\n{{\n    struct {n}_params *p = args;\n")
            c.write(f"    p->result = host.{n} ? host.{n}({args}) : XR_ERROR_FUNCTION_UNSUPPORTED;\n    return 0;\n}}\n\n")
        c.write("const unixlib_entry_t __wine_unix_call_funcs[] =\n{\n")
        for u in UNIX_CALLS:
            c.write(f"    bridge_{u},\n")
        for n in real:
            if n not in UNIX_SKIP:
                c.write(f"    thunk_{n},\n")
        c.write("};\n\n_Static_assert(ARRAY_SIZE(__wine_unix_call_funcs) == unix_count, \"call table\");\n")

    with open(os.path.join(out, "xr_host_functions.h"), "w") as h:
        h.write("/* Generated by bridge/make_openxr.py from xr.xml. */\n#pragma once\n\nstruct host_functions\n{\n")
        for n in host_side:
            h.write(f"    PFN_{n} {n};\n")
        h.write("};\n")


if __name__ == "__main__":
    main()
